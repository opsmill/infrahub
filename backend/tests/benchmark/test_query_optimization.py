"""Benchmark comparing pre-migration full-fetch vs. post-migration targeted queries.

The "full" queries reproduce what client.all() / client.filters() fetched before the
INFP-501 migration (all attributes + hfid + display_label).  The "optimized" queries are
generated by the actual query-model classes introduced in that migration.

Measures both execution time and response payload size to validate the optimization goals:
  SC-001: ≥30% execution time reduction per task
  SC-002: ≥50% data volume reduction per task

Run with:
  INFRAHUB_LOG_LEVEL=CRITICAL uv run pytest -v backend/tests/benchmark/test_query_optimization.py \
      --dist=no -s
"""

