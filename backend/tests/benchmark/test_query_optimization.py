import sys
import time
from typing import TYPE_CHECKING, Any

import pytest

from infrahub.core import registry
from infrahub.core.initialization import (
    create_default_branch,
    create_global_branch,
    create_root_node,
)
from infrahub.core.node import Node
from infrahub.core.schema import SchemaRoot, core_models, internal_schema
from infrahub.core.schema.manager import SchemaManager
from infrahub.core.utils import delete_all_nodes
from infrahub.display_labels.graphql_queries import DisplayLabelNodeIDQuery
from infrahub.git.graphql_queries import GitRepositoryNodeQuery
from infrahub.hfid.models import HFIDNodeIDQuery
from tests.helpers.graphql import graphql_query

if TYPE_CHECKING:
    from infrahub.core.branch import Branch
    from infrahub.core.schema.schema_branch import SchemaBranch
    from infrahub.database import InfrahubDatabase


NODE_COUNT = 200
ITERATIONS = 5
SC001_MIN_TIME_REDUCTION = 30
SC002_MIN_SIZE_REDUCTION = 50

FULL_TAG_QUERY = """
query PreMigrationBuiltinTagAll {
  BuiltinTag {
    edges {
      node {
        id
        hfid
        display_label
        __typename
        name { value is_default is_protected }
        description { value is_default is_protected }
      }
    }
  }
}
"""

FULL_REPO_QUERY = """
query PreMigrationCoreRepositoryFilters {
  CoreRepository {
    edges {
      node {
        id
        hfid
        display_label
        __typename
        name { value is_default is_protected }
        description { value is_default is_protected }
        location { value is_default is_protected }
        default_branch { value is_default is_protected }
        commit { value is_default is_protected }
        internal_status { value is_default is_protected }
        operational_status { value is_default is_protected }
        sync_status { value is_default is_protected }
      }
    }
  }
}
"""


@pytest.fixture(scope="module")
async def reset_environment(db: InfrahubDatabase) -> None:
    registry.delete_all()
    await delete_all_nodes(db=db)
    await create_root_node(db=db)


@pytest.fixture(scope="module")
async def default_branch(reset_environment: None, db: InfrahubDatabase) -> Branch:
    branch = await create_default_branch(db=db)
    await create_global_branch(db=db)
    registry.schema = SchemaManager()
    return branch


@pytest.fixture(scope="module")
async def register_default_schema(db: InfrahubDatabase, default_branch: Branch) -> SchemaBranch:
    schema_branch = registry.schema.get_schema_branch(name=default_branch.name)
    schema_branch.load_schema(schema=SchemaRoot(**internal_schema))
    schema_branch.load_schema(schema=SchemaRoot(**core_models))
    schema_branch.process()
    default_branch.update_schema_hash()
    await default_branch.save(db=db)
    return schema_branch


@pytest.fixture(scope="module")
async def benchmark_dataset(
    db: InfrahubDatabase,
    register_default_schema: SchemaBranch,
    default_branch: Branch,
) -> dict[str, Any]:
    """Create benchmark nodes. Returns metadata about what was created."""
    tag_ids = []
    for i in range(NODE_COUNT):
        tag = await Node.init(db=db, schema="BuiltinTag")
        await tag.new(db=db, name=f"bench-tag-{i:04d}", description=f"Benchmark tag number {i}")
        await tag.save(db=db)
        tag_ids.append(tag.id)

    repo_ids = []
    for i in range(NODE_COUNT):
        repo = await Node.init(db=db, schema="CoreRepository")
        await repo.new(
            db=db,
            name=f"bench-repo-{i:04d}",
            location=f"git@github.com:bench/repo-{i:04d}.git",
        )
        await repo.save(db=db)
        repo_ids.append(repo.id)

    return {"branch": default_branch, "tag_ids": tag_ids, "repo_ids": repo_ids}


def _payload_bytes(data: Any) -> int:
    return sys.getsizeof(json.dumps(data, default=str))


async def _time_query(db: InfrahubDatabase, branch: Branch, query: str, iterations: int) -> tuple[float, int]:
    """Returns (mean_seconds, payload_bytes_last_run)."""
    payload_bytes = 0
    times = []
    for _ in range(iterations):
        t0 = time.perf_counter()
        result = await graphql_query(query=query, db=db, branch=branch)
        elapsed = time.perf_counter() - t0
        assert result.errors is None, result.errors
        times.append(elapsed)
        payload_bytes = _payload_bytes(result.data)
    return sum(times) / len(times), payload_bytes


async def test_display_labels_migration(
    db: InfrahubDatabase,
    benchmark_dataset: dict[str, Any],
) -> None:
    """display_labels task: client.all(kind, exclude=...) → DisplayLabelNodeIDQuery."""
    branch: Branch = benchmark_dataset["branch"]

    optimized_query = DisplayLabelNodeIDQuery(kind="BuiltinTag").render_query()

    full_time, full_bytes = await _time_query(db, branch, FULL_TAG_QUERY, ITERATIONS)
    opt_time, opt_bytes = await _time_query(db, branch, optimized_query, ITERATIONS)

    time_reduction = (full_time - opt_time) / full_time * 100
    size_reduction = (full_bytes - opt_bytes) / full_bytes * 100

    print(f"\n{'=' * 60}")
    print(f"display_labels: BuiltinTag (n={NODE_COUNT}, iterations={ITERATIONS})")
    print("  client.all() full fetch  → DisplayLabelNodeIDQuery (id only)")
    print(f"{'=' * 60}")
    print(f"  Full fetch  : {full_time * 1000:.1f} ms  |  {full_bytes:,} bytes")
    print(f"  Optimized   : {opt_time * 1000:.1f} ms  |  {opt_bytes:,} bytes")
    print(f"  Time reduction : {time_reduction:.1f}%")
    print(f"  Size reduction : {size_reduction:.1f}%")

    assert opt_bytes < full_bytes, "Optimized query must produce a smaller payload"
    assert time_reduction >= SC001_MIN_TIME_REDUCTION, (
        f"Expected ≥{SC001_MIN_TIME_REDUCTION}% time reduction (SC-001), got {time_reduction:.1f}%"
    )
    assert size_reduction >= SC002_MIN_SIZE_REDUCTION, (
        f"Expected ≥{SC002_MIN_SIZE_REDUCTION}% size reduction (SC-002), got {size_reduction:.1f}%"
    )


